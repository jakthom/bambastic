func testSlicer(t *testing.T) (*Service, *http.ServeMux) {
	t.Helper()
	dir := t.TempDir()
	db := testdb.Open(t)
	s, e := New(db, dir)
	if e != nil {
		t.Fatal(e)
	}
	mux := http.NewServeMux()
	s.Register(mux)
	return s, mux
}
func call(t *testing.T, h http.Handler, p access.Principal, method, path, body string) (int, object) {
	t.Helper()
	w := httptest.NewRecorder()
	r := httptest.NewRequest(method, path, strings.NewReader(body))
	h.ServeHTTP(w, r.WithContext(access.With(r.Context(), p)))
	var o object
	if e := json.Unmarshal(w.Body.Bytes(), &o); e != nil {
		t.Fatalf("Invalid JSON %d %s", w.Code, w.Body.String())
	}
	return w.Code, o
}
func TestSidecarRoundTrip(t *testing.T) {
	s, h := testSlicer(t)
	farm, err := production.New(s.db, s.dir)
	if err != nil {
		t.Fatal(err)
	}
	s.AttachFarm(farm)
	mount := t.TempDir()
	t.Setenv("BAMBASTIC_EXTERNAL_ROOTS", mount)
	if err = os.WriteFile(filepath.Join(mount, "fixture.gcode.3mf"), []byte("existing"), 0600); err != nil {
		t.Fatal(err)
	}
	if _, err = s.db.Exec("INSERT INTO library_folders(name,is_external,external_readonly,external_show_hidden,external_path,shared) VALUES('Mount',1,0,0,?,1)", mount); err != nil {
		t.Fatal(err)
	}
	var output bytes.Buffer
	z := zip.NewWriter(&output)
	entry, _ := z.Create("Metadata/plate_1.gcode")
	entry.Write([]byte("; generated by slicer\nG1 X10\n"))
	z.Close()
	side := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path != "/slice" {
			http.NotFound(w, r)
			return
		}
		if e := r.ParseMultipartForm(10 << 20); e != nil {
			t.Error(e)
			return
		}
		defer r.MultipartForm.RemoveAll()
		f, header, e := r.FormFile("file")
		if e != nil {
			t.Error(e)
			return
		}
		defer f.Close()
		got, _ := io.ReadAll(f)
		if header.Filename != "fixture.stl" || string(got) != "model bytes" {
			t.Error("source model was not transferred")
		}
		if len(r.MultipartForm.File["filamentProfile"]) != 2 || r.FormValue("plate") != "0" || r.FormValue("exportType") != "3mf" || r.FormValue("requestId") == "" {
			t.Error("slice parameters or slot ordering lost")
		}
		f, _, e = r.FormFile("presetProfile")
		if e != nil {
			t.Error(e)
			return
		}
		defer f.Close()
		var proc object
		_ = json.NewDecoder(f).Decode(&proc)
		if proc["layer_height"] != "0.12" || proc["curr_bed_type"] != "High Temp Plate" {
			t.Errorf("process settings: %#v", proc)
		}
		w.Header().Set("X-Print-Time-Seconds", "123")
		w.Write(output.Bytes())
	}))
	defer side.Close()
	if _, e := s.db.Exec("INSERT INTO settings(key,value) VALUES('bambu_studio_api_url',?)", side.URL); e != nil {
		t.Fatal(e)
	}
	if e := os.WriteFile(filepath.Join(s.dir, "model.stl"), []byte("model bytes"), 0600); e != nil {
		t.Fatal(e)
	}
	if _, e := s.db.Exec("INSERT INTO library_files(filename,file_path,file_type,file_size,print_count,is_external,folder_id) VALUES('fixture.stl','model.stl','stl',11,0,1,1)"); e != nil {
		t.Fatal(e)
	}
	admin := access.Principal{Admin: true}
	code, o := call(t, h, admin, "POST", "/api/v1/local-presets/", `{"name":"PLA","preset_type":"filament","setting":{"filament_type":["PLA"]}}`)
	if code != 200 {
		t.Fatal(code, o)
	}
	body := `{"printer_preset":{"source":"standard","id":"Bambu Lab X1 Carbon 0.4 nozzle"},"process_preset":{"source":"standard","id":"Standard"},"filament_presets":[{"source":"local","id":"1"},{"source":"standard","id":"PETG"}],"filament_colours":["","#cc3388"],"plate":0,"process_overrides":{"layer_height":0.12},"bed_type":"Smooth PEI Plate"}`
	code, o = call(t, h, access.Principal{ID: 7, Permissions: map[string]bool{"library:upload": true, "library:read_own": true}}, "POST", "/api/v1/library/files/1/slice", body)
	if code != 404 {
		t.Fatal("cross-owner slice", code, o)
	}
	code, o = call(t, h, admin, "POST", "/api/v1/library/files/1/slice", body)
	if code != 202 {
		t.Fatal(code, o)
	}
	statusURL := o["status_url"].(string)
	deadline := time.Now().Add(5 * time.Second)
	for time.Now().Before(deadline) {
		_, o = call(t, h, admin, "GET", statusURL, "")
		if o["status"] == "completed" || o["status"] == "failed" {
			break
		}
		time.Sleep(5 * time.Millisecond)
	}
	if o["status"] != "completed" {
		t.Fatal(o)
	}
	out := o["result"].(map[string]any)
	if out["library_file_id"] != float64(2) || out["print_time_seconds"] != float64(123) {
		t.Fatal(out)
	}
	if out["name"] != "fixture (2).gcode.3mf" {
		t.Fatal(out)
	}
	mirrored, e := os.ReadFile(filepath.Join(mount, "fixture (2).gcode.3mf"))
	if e != nil || !bytes.Equal(mirrored, output.Bytes()) {
		t.Fatal("slice missing on external volume", e)
	}
	var file string
	if e := s.db.QueryRow("SELECT file_path FROM library_files WHERE id=2 AND file_type='gcode.3mf' AND is_external=1").Scan(&file); e != nil {
		t.Fatal(e)
	}
	b, e := os.ReadFile(filepath.Join(s.dir, file))
	if e != nil || !bytes.Equal(b, output.Bytes()) {
		t.Fatal("published file mismatch", e)
	}
}

func TestCloseJoinsOutstandingJob(t *testing.T) {
	s, _ := testSlicer(t)
	began := make(chan struct{})
	stopped := make(chan struct{})
	side := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.URL.Path != "/slice" {
			http.NotFound(w, r)
			return
		}
		_, _ = io.Copy(io.Discard, r.Body)
		close(began)
		<-r.Context().Done()
		close(stopped)
	}))
	defer side.Close()
	p := filepath.Join(s.dir, "source.stl")
	if e := os.WriteFile(p, []byte("input"), 0600); e != nil {
		t.Fatal(e)
	}
	f, e := os.Open(p)
	if e != nil {
		t.Fatal(e)
	}
	complete := make(chan struct{})
	_, e = s.startJob(access.Principal{Admin: true}, sourceFile{name: "part.stl"}, "library_file", false, sliceRequest{}, recipe{}, side.URL, f, func(object, error) { close(complete) })
	if e != nil {
		t.Fatal(e)
	}
	select {
	case <-began:
	case <-time.After(time.Second):
		t.Fatal("sidecar not reached")
	}
	s.Close()
	select {
	case <-complete:
	default:
		t.Fatal("job callback outlived Close")
	}
	select {
	case <-stopped:
	case <-time.After(time.Second):
		t.Fatal("sidecar request still running")
	}
	f, _ = os.Open(p)
	if _, e = s.startJob(access.Principal{Admin: true}, sourceFile{name: "part.stl"}, "library_file", false, sliceRequest{}, recipe{}, side.URL, f, nil); e == nil {
		t.Fatal("closed service accepted a job")
	}
}
