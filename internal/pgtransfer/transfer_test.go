// A private Unix socket makes this test independent of a developer's existing
// PostgreSQL server. The temporary fixture has no TCP listener.
func privateCluster(t *testing.T) string {
	t.Helper()
	if _, err := exec.LookPath("initdb"); err != nil || os.Getuid() == 0 {
		t.Skip("private PG16 fixture needs PostgreSQL 16+ binaries on PATH and a non-root user")
	}
	dir, err := os.MkdirTemp("/tmp", "bb-portable-pg-")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { os.RemoveAll(dir) })
	data := filepath.Join(dir, "data")
	run := func(name string, args ...string) {
		t.Helper()
		if out, e := exec.Command(name, args...).CombinedOutput(); e != nil {
			t.Fatalf("%s: %s %v", name, out, e)
		}
	}
	run("initdb", "-D", data, "-U", "fixture", "--auth-local=trust", "--auth-host=reject", "--no-locale", "--encoding=UTF8")
	run("pg_ctl", "-D", data, "-l", filepath.Join(dir, "server.log"), "-o", "-c listen_addresses='' -k "+dir+" -p 55434", "-w", "start")
	t.Cleanup(func() { run("pg_ctl", "-D", data, "-m", "fast", "-w", "stop") })
	return "postgres://fixture@/postgres?host=" + url.QueryEscape(dir) + "&port=55434"
}

const sqliteFixture = `
CREATE TABLE print_archives(id INTEGER PRIMARY KEY AUTOINCREMENT,title TEXT NOT NULL, project_id INTEGER REFERENCES projects(id));
CREATE TABLE projects(id INTEGER PRIMARY KEY, sample_archive INTEGER REFERENCES print_archives(id), parent_id INTEGER REFERENCES projects(id));
CREATE TABLE bb_material_sample(id INTEGER PRIMARY KEY AUTOINCREMENT, project_id INTEGER NOT NULL REFERENCES projects(id), weight NUMERIC(14,4), measured DATETIME NOT NULL,cycle DATE NOT NULL, settings TEXT, packed BLOB, enabled BOOLEAN NOT NULL, optional TEXT);
CREATE TABLE bb_events(id INTEGER PRIMARY KEY AUTOINCREMENT,summary TEXT NOT NULL);
CREATE TRIGGER audit_changes AFTER INSERT ON bb_material_sample BEGIN INSERT INTO bb_events(summary) VALUES('new sample'); END;
CREATE VIRTUAL TABLE archive_fts USING fts5(title,content='print_archives',content_rowid='id');
CREATE TRIGGER archive_fts_add AFTER INSERT ON print_archives BEGIN INSERT INTO archive_fts(rowid,title) VALUES(new.id,new.title); END;`
const pgFixture = `
CREATE TABLE print_archives(id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,title TEXT NOT NULL, project_id BIGINT);
CREATE TABLE projects(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,sample_archive BIGINT REFERENCES print_archives(id),parent_id BIGINT REFERENCES projects(id));
ALTER TABLE print_archives ADD FOREIGN KEY(project_id) REFERENCES projects(id);
CREATE TABLE bb_material_sample(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id BIGINT NOT NULL REFERENCES projects(id), weight NUMERIC(14,4), measured TIMESTAMPTZ NOT NULL, cycle DATE NOT NULL, settings TEXT, packed BYTEA, enabled BOOLEAN NOT NULL, optional TEXT);
CREATE TABLE bb_events(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,summary TEXT NOT NULL);
CREATE FUNCTION audit_changes() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN INSERT INTO bb_events(summary) VALUES('new sample'); RETURN NEW; END $$;
CREATE TRIGGER audit_changes AFTER INSERT ON bb_material_sample FOR EACH ROW EXECUTE FUNCTION audit_changes();`

func execute(t *testing.T, db *sql.DB, stmt string, args ...any) {
	t.Helper()
	if _, e := db.ExecContext(t.Context(), stmt, args...); e != nil {
		t.Fatalf("%v in %.80s", e, stmt)
	}
}
func integer(t *testing.T, db *sql.DB, want int64, query string) {
	t.Helper()
	var n int64
	if e := db.QueryRowContext(t.Context(), query).Scan(&n); e != nil || n != want {
		t.Fatalf("%s: got %d, want %d, err=%v", query, n, want, e)
	}
}
func sqliteDB(t *testing.T, ddl string) *sql.DB {
	t.Helper()
	db, e := sql.Open("sqlite", filepath.Join(t.TempDir(), "farm.db")+"?_pragma=foreign_keys(1)")
	if e != nil {
		t.Fatal(e)
	}
	db.SetMaxOpenConns(1)
	t.Cleanup(func() { db.Close() })
	execute(t, db, ddl)
	return db
}
func pgDB(t *testing.T, dsn, schema, ddl string) *sql.DB {
	t.Helper()
	db, e := postgres.Raw(t.Context(), dsn, schema)
	if e != nil {
		t.Fatal(e)
	}
	t.Cleanup(func() { db.Close() })
	execute(t, db, "CREATE SCHEMA "+quote(schema))
	execute(t, db, ddl)
	return db
}
func populated(t *testing.T, db *sql.DB) {
	t.Helper()
	execute(t, db, `BEGIN;
	PRAGMA defer_foreign_keys=ON;
	INSERT INTO print_archives(id,title,project_id) VALUES(12,'needle search',4);
	INSERT INTO projects(id,sample_archive,parent_id) VALUES(4,12,4);
	INSERT INTO bb_material_sample(id,project_id,weight,measured,cycle,settings,packed,enabled) VALUES(6,4,1234.5401,'2025-01-02T01:02:03.234567+01:00','2025-02-11','{"color":"blue"}',X'00FF01',1);
	INSERT INTO bb_material_sample(id,project_id,weight,measured,cycle,enabled) VALUES(100,4,0,'2025-01-02','2025-01-12',0);
	DELETE FROM bb_material_sample WHERE id=100;
	COMMIT`)
}
func TestPortableGeneration(t *testing.T) {
	dsn := privateCluster(t)
	source := sqliteDB(t, sqliteFixture)
	populated(t, source)
	pg := pgDB(t, dsn, "bb_transfer_roundtrip", pgFixture)
	var ver int
	if err := pg.QueryRow("SHOW server_version_num").Scan(&ver); err != nil || ver < 160000 {
		t.Fatalf("need PostgreSQL >=16, got %d %v", ver, err)
	}
	if e := Import(t.Context(), source, pg); e != nil {
		t.Fatal("import", e)
	}
	integer(t, pg, 2, "SELECT count(*) FROM bb_events")
	integer(t, pg, 1, "SELECT count(*) FROM bb_pg_transfer_state WHERE one=1 AND imported")
	var monetary, day, settings string
	var ts time.Time
	var blob []byte
	var enabled bool
	var optional sql.NullString
	e := pg.QueryRow("SELECT weight::text,cycle::text,measured,settings,packed,enabled,optional FROM bb_material_sample WHERE id=6").Scan(&monetary, &day, &ts, &settings, &blob, &enabled, &optional)
	if e != nil || monetary != "1234.5401" || day != "2025-02-11" || !ts.Equal(time.Date(2025, 1, 2, 0, 2, 3, 234567000, time.UTC)) || settings != `{"color":"blue"}` || !bytes.Equal(blob, []byte{0, 255, 1}) || !enabled || optional.Valid {
		t.Fatalf("field conversion %q %q %v %#v %x %v %v %v", monetary, day, ts, settings, blob, enabled, optional, e)
	}
	if e = Import(t.Context(), source, pg); e == nil || !strings.Contains(e.Error(), "already contains an imported") {
		t.Fatalf("import replay: %v", e)
	}
	// Capture identity history even on ordinary SQLite INTEGER PRIMARY KEY,
	// which has no sqlite_sequence. The next deleted project ID must stay spent.
	integer(t, pg, 50, "SELECT setval(pg_get_serial_sequence('projects','id'),50)")
	backup := sqliteDB(t, sqliteFixture)
	if e = Export(t.Context(), pg, backup); e != nil {
		t.Fatal("export", e)
	}
	integer(t, backup, 1, "SELECT count(*) FROM archive_fts WHERE archive_fts MATCH 'needle'")
	integer(t, backup, 2, "SELECT count(*) FROM bb_events")
	integer(t, backup, 0, "SELECT count(*) FROM sqlite_schema WHERE name='bb_pg_transfer_state'")
	integer(t, backup, 0, "SELECT count(*) FROM pragma_foreign_key_check")
	integer(t, backup, 1, "PRAGMA foreign_keys")
	var date string
	if e = backup.QueryRow("SELECT CAST(cycle AS TEXT) FROM bb_material_sample WHERE id=6").Scan(&date); e != nil || date != "2025-02-11" {
		t.Fatalf("date %q %v", date, e)
	}
	pg2 := pgDB(t, dsn, "bb_transfer_second", pgFixture)
	if e = Import(t.Context(), backup, pg2); e != nil {
		t.Fatal("restore exported backup", e)
	}
	integer(t, pg2, 51, "SELECT nextval(pg_get_serial_sequence('projects','id'))")
	integer(t, pg2, 101, "SELECT nextval(pg_get_serial_sequence('bb_material_sample','id'))")
	execute(t, backup, "INSERT INTO bb_material_sample(project_id,measured,cycle,enabled) VALUES(4,'2025-01-02','2025-01-12',0)")
	integer(t, backup, 101, "SELECT max(id) FROM bb_material_sample")
	integer(t, backup, 3, "SELECT count(*) FROM bb_events")
	if e = Export(t.Context(), pg, backup); e == nil {
		t.Fatal("overwrote an existing SQLite farm")
	}
	t.Run("invalid foreign keys roll back data, sequences, trigger and marker", func(t *testing.T) {
		raw := pgDB(t, dsn, "bb_transfer_rollback", pgFixture)
		bad := sqliteDB(t, sqliteFixture)
		populated(t, bad)
		execute(t, bad, "PRAGMA foreign_keys=OFF")
		execute(t, bad, "UPDATE bb_material_sample SET project_id=424242")
		if e := Import(t.Context(), bad, raw); e == nil || !strings.Contains(e.Error(), "foreign key") {
			t.Fatalf("unexpected import result %v", e)
		}
		integer(t, raw, 0, "SELECT count(*) FROM bb_material_sample")
		integer(t, raw, 0, "SELECT count(*) FROM bb_events")
		integer(t, raw, 0, "SELECT count(*) FROM information_schema.tables WHERE table_schema=current_schema() AND table_name='bb_pg_transfer_state'")
		integer(t, raw, 0, "SELECT count(*) FROM pg_constraint WHERE connamespace=current_schema()::regnamespace AND contype='f' AND condeferrable")
		integer(t, raw, 1, "SELECT count(*) FROM pg_trigger WHERE tgrelid='bb_material_sample'::regclass AND tgname='audit_changes' AND tgenabled='O'")
		integer(t, raw, 1, "SELECT nextval(pg_get_serial_sequence('bb_material_sample','id'))")
		execute(t, raw, "INSERT INTO projects(id) VALUES(71)")
		if e := Import(t.Context(), source, raw); e == nil || !strings.Contains(e.Error(), "already contains data") {
			t.Fatalf("expected populated database refusal, got %v", e)
		}
		integer(t, raw, 71, "SELECT id FROM projects")
	})
	t.Run("release schema", func(t *testing.T) {
		ddl, e := os.ReadFile("../../spec/storage.sql")
		if e != nil {
			t.Fatal(e)
		}
		app, e := postgres.Open(t.Context(), dsn, "bb_release_snapshot")
		if e != nil {
			t.Fatal(e)
		}
		defer app.Close()
		if e = postgres.Bootstrap(t.Context(), app, string(ddl)); e != nil {
			t.Fatal(e)
		}
		release, e := postgres.Raw(t.Context(), dsn, "bb_release_snapshot")
		if e != nil {
			t.Fatal(e)
		}
		defer release.Close()
		export := sqliteDB(t, string(ddl))
		initial := sqliteDB(t, string(ddl))
		for _, db := range []*sql.DB{app, export, initial} {
			db.SetMaxOpenConns(6)
			if _, e = access.New(db, t.TempDir()); e != nil {
				t.Fatal(e)
			}
			if _, e = management.New(db); e != nil {
				t.Fatal(e)
			}
			if _, e = operations.New(db); e != nil {
				t.Fatal(e)
			}
			if _, e = support.New(db); e != nil {
				t.Fatal(e)
			}
		}
		execute(t, initial, "INSERT INTO locations(id,name,name_key) VALUES(25,'Bay A','bay a')")
		if e = Import(t.Context(), initial, release); e != nil {
			t.Fatal("native baseline import", e)
		}
		if e = Export(t.Context(), release, export); e != nil {
			t.Fatal("native baseline export", e)
		}
		integer(t, export, 25, "SELECT id FROM locations")
	})
}
func TestRejectsEditedDefaultSettings(t *testing.T) {
	db := sqliteDB(t, "CREATE TABLE settings(key TEXT PRIMARY KEY,value TEXT);INSERT INTO settings VALUES('bambastic_catalogs_initialized','true')")
	tx, e := db.Begin()
	if e != nil {
		t.Fatal(e)
	}
	defer tx.Rollback()
	c, e := sqliteCatalog(context.Background(), tx)
	if e != nil {
		t.Fatal(e)
	}
	if e = checkDestination(t.Context(), tx, c); e != nil {
		t.Fatal(e)
	}
	if _, e = tx.Exec("UPDATE settings SET value='false'"); e != nil {
		t.Fatal(e)
	}
	if e = checkDestination(t.Context(), tx, c); e == nil || !strings.Contains(fmt.Sprint(e), "modified defaults") {
		t.Fatalf("got %v", e)
	}
}
